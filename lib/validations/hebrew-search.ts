/**
 * נרמול מונח חיפוש בעברית (משימה 3.8, FR-CL-06).
 *
 * שתי פעולות נרמול:
 * 1. הסרת ניקוד (תווי נקודה, שווא, חיריק וכו׳ — טווח Unicode U+05B0–U+05C7)
 *    כך שמונח כמו "שַׁבָּת" ייאסף כ"שבת".
 * 2. הסרת תחילית יחידה ה/ו/ב מתחילת המונח, כך שהחיפוש "הגיעה" → "גיעה",
 *    "בטיפול" → "טיפול", "וגם" → "גם".
 *
 * חשוב: הנרמול מתבצע על מונח החיפוש בלבד — לא על הנתונים ב-DB, שנשמרים
 * כרגיל. זה מספיק לכסות את קריטריוני הקבלה של המשימה (FR-CL-06).
 *
 * פונקציה טהורה (pure) — ניתנת לבדיקה ללא DB.
 */

/** טווח תווי ניקוד עברי ב-Unicode (U+05B0–U+05C7). */
const NIKUD_RANGE_RE = /[ְ-ׇ]/g;

/** תחיליות עבריות נפוצות: ה (ה׳ הידיעה), ו (חיבור), ב (בתוך). */
const HEBREW_PREFIX_RE = /^[הוב]/;

/**
 * מחזיר את מונח החיפוש אחרי:
 * 1. הסרת ניקוד (אם קיים).
 * 2. הסרת תחילית אחת (ה/ו/ב) מתחילת המונח.
 *
 * דוגמאות:
 *   "בטיפול"  → "טיפול"
 *   "הגיעה"   → "גיעה"
 *   "וגם"     → "גם"
 *   "ה"       → ""
 *   "טיפול"   → "טיפול"  (אין תחילית — נשאר כמו שהוא)
 *   ""        → ""
 */
export function normalizeHebrewSearchTerm(term: string): string {
  if (!term) return "";

  // שלב 1: הסרת ניקוד
  const withoutNikud = term.replace(NIKUD_RANGE_RE, "");

  // שלב 2: הסרת תחילית יחידה ה/ו/ב
  const withoutPrefix = withoutNikud.replace(HEBREW_PREFIX_RE, "");

  return withoutPrefix;
}
